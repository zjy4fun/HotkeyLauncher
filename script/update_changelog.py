#!/usr/bin/env python3
"""Generate CHANGELOG.md and release notes with GitHub's PR/author attribution."""

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import subprocess
import sys


VERSION = re.compile(r"v(\d+)\.(\d+)\.(\d+)\Z")


def github_api(endpoint, method="GET", fields=None, paginate=False):
    command = ["gh", "api", endpoint, "--method", method]
    if paginate:
        command += ["--paginate", "--slurp"]
    for key, value in (fields or {}).items():
        command += ["--raw-field", f"{key}={value}"]
    result = subprocess.run(command, check=True, text=True, capture_output=True)
    return json.loads(result.stdout)


def version_key(tag):
    match = VERSION.fullmatch(tag)
    if not match:
        raise ValueError(f"Expected a stable version tag such as v1.0.11: {tag}")
    return tuple(int(part) for part in match.groups())


def commit_notes(repository, tag, previous=None):
    if previous:
        endpoint = f"repos/{repository}/compare/{previous}...{tag}?per_page=100"
    else:
        endpoint = f"repos/{repository}/commits?sha={tag}&per_page=100"
    pages = github_api(endpoint, paginate=True)
    commits = [
        commit for page in pages for commit in (page["commits"] if previous else page)
    ]
    entries = []
    for commit in commits:
        if len(commit["parents"]) > 1:
            continue
        title = commit["commit"]["message"].splitlines()[0]
        author = commit.get("author")
        name = f"@{author['login']}" if author else commit["commit"]["author"]["name"]
        entries.append(f"* {title} by {name} in {commit['html_url']}")
    return "## Commits\n" + "\n".join(entries) if entries else ""


def generate(repository, releases, tag=None):
    published = {
        release["tag_name"]: release
        for release in releases
        if not release["draft"]
        and not release["prerelease"]
        and VERSION.fullmatch(release["tag_name"])
    }
    if tag and tag not in published:
        published[tag] = {
            "tag_name": tag,
            "published_at": datetime.now(timezone.utc).isoformat(),
            "html_url": f"https://github.com/{repository}/releases/tag/{tag}",
        }

    notes = {}
    versions = sorted(published, key=version_key)
    for index, version in enumerate(versions):
        fields = {"tag_name": version}
        if index:
            fields["previous_tag_name"] = versions[index - 1]
        response = github_api(
            f"repos/{repository}/releases/generate-notes", "POST", fields
        )
        body = response["body"].strip()
        if not body or body.startswith("**Full Changelog**:"):
            commits = commit_notes(repository, version, versions[index - 1] if index else None)
            body = "\n\n".join(part for part in (commits, body) if part)
        notes[version] = body

    sections = [
        "# Changelog\n\n"
        "Generated by `python3 script/update_changelog.py` from GitHub release "
        "notes. Pull request entries include their authors and links.\n"
    ]
    for version in reversed(versions):
        release = published[version]
        date = release["published_at"][:10]
        body = re.sub(r"(?m)^(#{1,5}) ", r"\1# ", notes[version])
        sections.append(
            f"## [{version}]({release['html_url']}) — {date}\n\n{body}\n"
        )
    return "\n".join(sections), notes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", default=os.environ.get("GITHUB_REPOSITORY"))
    parser.add_argument("--tag", help="Include a stable tag before its Release exists")
    parser.add_argument("--output", type=Path, default=Path("CHANGELOG.md"))
    parser.add_argument("--notes-output", type=Path, help="Write notes for --tag")
    args = parser.parse_args()
    if args.notes_output and not args.tag:
        parser.error("--notes-output requires --tag")
    if args.tag:
        try:
            version_key(args.tag)
        except ValueError as error:
            parser.error(str(error))

    repository = args.repository
    if not repository:
        repository = subprocess.run(
            ["gh", "repo", "view", "--json", "nameWithOwner", "--jq", ".nameWithOwner"],
            check=True, text=True, capture_output=True,
        ).stdout.strip()
    pages = github_api(f"repos/{repository}/releases?per_page=100", paginate=True)
    releases = [release for page in pages for release in page]
    changelog, notes = generate(repository, releases, args.tag)
    args.output.write_text(changelog, encoding="utf-8")
    if args.notes_output:
        args.notes_output.write_text(notes[args.tag] + "\n", encoding="utf-8")
    print(f"Updated {args.output} with {len(notes)} stable releases.")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        print(error.stderr or str(error), file=sys.stderr)
        sys.exit(1)
